export function getMagazineArticle(slug: string) {
  return magazineArticles.find((article) => article.slug === slug);
}

export function getRelatedArticles(article: MagazineArticle, limit = 3) {
  const sameCategory = magazineArticles.filter(
    (item) => item.slug !== article.slug && item.category === article.category
  );
  const others = magazineArticles.filter(
    (item) => item.slug !== article.slug && item.category !== article.category
  );

  return [...sameCategory, ...others].slice(0, limit);
}
